// This file tests the explicit setup action against real temporary profile
// directories. Nothing here touches the developer's own ~/.omp tree: every
// profile, plugin root and state directory is created under t.TempDir().
//
// `herdr integration status` is a real child process. TestMain turns this test
// binary into a stand-in Herdr CLI (selected by SETUP_FIXTURE_STATUS_FILE) so
// the status check, its exit status and the argv it was called with are
// observed through exec, never through a mock.

const (
	fixtureStatusFile = "SETUP_FIXTURE_STATUS_FILE"
	fixtureStderrFile = "SETUP_FIXTURE_STDERR_FILE"
	fixtureExitCode   = "SETUP_FIXTURE_EXIT_CODE"
	fixtureArgvFile   = "SETUP_FIXTURE_ARGV_FILE"
)

func TestMain(m *testing.M) {
	if path := os.Getenv(fixtureStatusFile); path != "" {
		os.Exit(runStatusFixture(path))
	}
	os.Exit(m.Run())
}

// runStatusFixture behaves like `herdr integration status`: it prints the
// configured report on stdout, records argv, and exits with the configured
// status (a non-zero status writes the report to stderr, the way the real CLI
// prints failures there).
func runStatusFixture(path string) int {
	if argvPath := os.Getenv(fixtureArgvFile); argvPath != "" {
		if err := os.WriteFile(argvPath, []byte(strings.Join(os.Args[1:], " ")), 0o600); err != nil {
			return 11
		}
	}
	report, err := os.ReadFile(path)
	if err != nil {
		return 12
	}
	code := 0
	if raw := os.Getenv(fixtureExitCode); raw != "" {
		parsed, err := strconv.Atoi(raw)
		if err != nil {
			return 13
		}
		code = parsed
	}
	if code != 0 {
		_, _ = os.Stderr.Write(report)
		return code
	}
	_, _ = os.Stdout.Write(report)
	return 0
}

