func TestInstallWritesOnlyItsOwnExtension(t *testing.T) {
	f := newFixture(t)
	herdrIntegration := f.installIntegration(t, "")
	before, err := os.ReadFile(herdrIntegration)
	if err != nil {
		t.Fatalf("read Herdr integration: %v", err)
	}

	if err := f.install(); err != nil {
		t.Fatalf("Install: %v", err)
	}

	target := f.extensionPath("")
	content, err := os.ReadFile(target)
	if err != nil {
		t.Fatalf("read generated extension: %v", err)
	}
	after, err := os.ReadFile(herdrIntegration)
	if err != nil {
		t.Fatalf("re-read Herdr integration: %v", err)
	}
	if string(before) != string(after) {
		t.Errorf("Herdr's integration file changed:\nbefore: %q\nafter:  %q", before, after)
	}

	if !strings.HasPrefix(string(content), ManagedMarker+"\n") {
		t.Errorf("generated extension does not start with the managed marker:\n%s", content)
	}
	for _, want := range []string{
		"const PLUGIN_EXECUTABLE = " + jsQuote(t, f.exe) + ";",
		"const STATE_DIR = " + jsQuote(t, f.stateDir) + ";",
		"const HERDR_BINARY = " + jsQuote(t, f.env["HERDR_BIN_PATH"]) + ";",
		"const PROTOCOL = 1;",
	} {
		if !strings.Contains(string(content), want) {
			t.Errorf("generated extension is missing %q:\n%s", want, content)
		}
	}
	if strings.Contains(string(content), PlaceholderExecutable) ||
		strings.Contains(string(content), PlaceholderStateDir) ||
		strings.Contains(string(content), PlaceholderHerdrBin) {
		t.Errorf("generated extension still contains a placeholder:\n%s", content)
	}

	entries, err := os.ReadDir(filepath.Dir(target))
	if err != nil {
		t.Fatalf("read extensions dir: %v", err)
	}
	var names []string
	for _, e := range entries {
		names = append(names, e.Name())
	}
	if len(names) != 2 {
		t.Errorf("extensions dir holds %v, want only the generated extension and Herdr's file", names)
	}
	for _, name := range names {
		if strings.HasPrefix(name, ".") || strings.HasSuffix(name, ".tmp") {
			t.Errorf("install left a temporary file behind: %q", name)
		}
	}
}

