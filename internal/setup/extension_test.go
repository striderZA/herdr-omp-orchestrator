func TestInstallEmbedsEscapedPathsThatDecodeBackToTheEnvironment(t *testing.T) {
	f := newFixture(t)
	// Windows forbids '"' and newlines in file names, so the escaping is proven
	// where it matters on this platform: every backslash in the path must be
	// escaped in the literal and decode back to the exact path the environment
	// supplied. Spaces and non-ASCII characters must survive untouched.
	odd := filepath.Join(t.TempDir(), "plugin %odd% ünïcode dir")
	if err := os.MkdirAll(odd, 0o755); err != nil {
		t.Fatalf("create odd directory: %v", err)
	}
	f.exe = filepath.Join(odd, "herdr-omp-orchestrator.exe")
	writeFile(t, f.exe, "MZ stand-in plugin executable")
	f.stateDir = filepath.Join(odd, "state")
	f.env["HERDR_PLUGIN_STATE_DIR"] = f.stateDir
	f.installIntegration(t, "")

	if err := f.install(); err != nil {
		t.Fatalf("Install: %v", err)
	}
	content, err := os.ReadFile(f.extensionPath(""))
	if err != nil {
		t.Fatalf("read generated extension: %v", err)
	}
	for _, want := range []struct{ label, value string }{
		{"PLUGIN_EXECUTABLE", f.exe},
		{"STATE_DIR", f.stateDir},
	} {
		line := "const " + want.label + " = "
		index := strings.Index(string(content), line)
		if index < 0 {
			t.Fatalf("generated extension has no %s line:\n%s", want.label, content)
		}
		rest := string(content)[index+len(line):]
		end := strings.Index(rest, ";\n")
		if end < 0 {
			t.Fatalf("generated extension has an unterminated %s literal:\n%s", want.label, content)
		}
		literal := rest[:end]
		var decoded string
		if err := json.Unmarshal([]byte(literal), &decoded); err != nil {
			t.Fatalf("decode %s literal %s: %v", want.label, literal, err)
		}
		if decoded != want.value {
			t.Errorf("%s decodes to %q, want %q", want.label, decoded, want.value)
		}
		if strings.Contains(string(content), line+`"`+want.value+`";`) {
			t.Errorf("%s was embedded unescaped; the literal %s must escape path separators", want.label, literal)
		}
	}
}

