func TestInstallRejectsUnavailableExecutable(t *testing.T) {
	f := newFixture(t)
	f.installIntegration(t, "")
	target := f.extensionPath("")

	for _, tc := range []struct {
		name string
		exe  string
	}{
		{"missing", filepath.Join(t.TempDir(), "gone.exe")},
		{"directory", t.TempDir()},
		{"empty", ""},
	} {
		t.Run(tc.name, func(t *testing.T) {
			err := Install(f.env, tc.exe)
			if !errors.Is(err, ErrExecutableUnavailable) {
				t.Fatalf("Install(%q) = %v, want ErrExecutableUnavailable", tc.exe, err)
			}
			if strings.TrimSpace(tc.exe) != "" && !strings.Contains(err.Error(), tc.exe) {
				t.Errorf("error %q does not name the stale executable %q", err, tc.exe)
			}
			if _, statErr := os.Stat(target); !os.IsNotExist(statErr) {
				t.Errorf("install wrote %s despite a stale executable (stat err = %v)", target, statErr)
			}
		})
	}
}

func TestInstallRefusesConflictingUnmanagedExtension(t *testing.T) {
	f := newFixture(t)
	f.installIntegration(t, "")
	target := f.extensionPath("")
	foreign := "// an extension this plugin did not generate\nexport default () => {};\n"
	writeFile(t, target, foreign)

	err := f.install()
	if !errors.Is(err, ErrExtensionConflict) {
		t.Fatalf("Install over an unmanaged extension = %v, want ErrExtensionConflict", err)
	}
	content, readErr := os.ReadFile(target)
	if readErr != nil {
		t.Fatalf("read conflicting extension: %v", readErr)
	}
	if string(content) != foreign {
		t.Errorf("install modified the conflicting extension:\n%s", content)
	}
}

